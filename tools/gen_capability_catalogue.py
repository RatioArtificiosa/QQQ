"""Generate `schema/capability-catalogue.tsv` from the three Q-Block sources (`REG-013`).

# Why generated rather than written

Proposal §4.8.8 step 10 requires the namespace count test and the catalogue to
move with the vocabulary. A hand-maintained table drifts from the three sources
that define it -- the capability names in `qqq-cap/src/capability.rs`, the
`implemented` flags in `qqq-abi/src/registry.rs`, and the manifest stanzas in
`qqq-cap/src/manifest.rs` -- and the drift is invisible, because both documents
read as authoritative. Generating removes the possibility: `--check` fails the
gate when the committed file disagrees with the tree.

# What the catalogue is

One row per capability (24), sorted by dotted name. Columns:

| Column | Source | Meaning |
|---|---|---|
| `namespace` | `Capability::name` root | the bindable namespace |
| `capability` | `Capability::name` | the stable dotted name |
| `kind` | `Capability::kind` | `resource`, `operation` or `ambient` |
| `bound` | registry `implemented` flag | whether the host serves it today |
| `interface` | registry row | the exact `qqq:<ns>@<ver>` that unlocks it |
| `stanza` | `Capabilities` struct field | the `[capabilities.<ns>]` spelling |

Usage:
    python tools/gen_capability_catalogue.py            # write schema/capability-catalogue.tsv
    python tools/gen_capability_catalogue.py --check    # fail if it is out of date
    python tools/gen_capability_catalogue.py --self-test  # prove the parsers detect breakage
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# This tool's own stdout must be able to encode what it prints. On a Windows console the stream
# inherits `cp1252`, so a character read from a subprocess -- which this file now reads as UTF-8 --
# raises `UnicodeEncodeError` inside `print` and the tool dies while reporting its result. `§O-291`.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError):  # pragma: no cover - a replaced stream
        pass


ROOT = Path(__file__).resolve().parent.parent
CAPABILITY_RS = ROOT / "crates" / "qqq-cap" / "src" / "capability.rs"
REGISTRY_RS = ROOT / "crates" / "qqq-abi" / "src" / "registry.rs"
MANIFEST_RS = ROOT / "crates" / "qqq-cap" / "src" / "manifest.rs"
CATALOGUE = ROOT / "schema" / "capability-catalogue.tsv"

HEADER = """\
# GENERATED FILE -- DO NOT EDIT BY HAND.
#
# Source:      crates/qqq-cap/src/capability.rs (names, kinds)
#              crates/qqq-abi/src/registry.rs (implemented flags, interfaces)
#              crates/qqq-cap/src/manifest.rs (stanza fields)
# Generated by: python tools/gen_capability_catalogue.py
# Verified by:  python tools/gen_capability_catalogue.py --check  (runs in CI)
#
# Edit the sources instead. --check fails the build when this file and the
# tree disagree, so a hand-edit here is caught rather than silently kept.
namespace\tcapability\tkind\tbound\tinterface\tstanza
"""


def parse_names(text: str) -> dict[str, str]:
    """Variant -> dotted name, from the `Capability::name` body."""
    start = text.find("pub const fn name(self)")
    if start < 0:
        raise ValueError("Capability::name not found")
    end = text.find("pub fn namespace(self)", start)
    body = text[start : end if end > 0 else len(text)]
    out: dict[str, str] = {}
    for line in body.splitlines():
        line = line.strip()
        m = re.match(r"Self::([A-Za-z0-9_]+) => \"([a-z]+\.[a-z]+)\",$", line)
        if m:
            out[m.group(1)] = m.group(2)
    if not out:
        raise ValueError("no name() arms parsed; the function moved")
    return out


def parse_kinds(text: str) -> dict[str, str]:
    """Variant -> kind, from the `Capability::kind` body.

    Arms list variants with `|` continuations; a variant may appear on the
    `=>` line or on any continuation line above it.
    """
    start = text.find("pub const fn kind(self)")
    if start < 0:
        raise ValueError("Capability::kind not found")
    end = text.find("pub const fn is_covert_channel", start)
    body = text[start : end if end > 0 else len(text)]
    out: dict[str, str] = {}
    pending: list[str] = []
    for line in body.splitlines():
        line = line.strip()
        for variant in re.findall(r"Self::([A-Za-z0-9_]+)", line):
            pending.append(variant)
        m = re.search(r"=> CapabilityKind::([A-Za-z]+),", line)
        if m:
            kind = m.group(1).lower()
            for variant in pending:
                out[variant] = kind
            pending = []
    if pending:
        raise ValueError(f"kind() variants without a kind arm: {pending}")
    if not out:
        raise ValueError("no kind() arms parsed; the function moved")
    return out


def parse_registry(text: str) -> dict[str, tuple[str, bool]]:
    """Variant -> (interface name, implemented), from the `iface(` entries."""
    out: dict[str, tuple[str, bool]] = {}
    for block in re.findall(r"(?ms)^\s*iface\(\s*^(.*?)^\s*\),", text):
        name = re.search(r'(?m)^\s*"(qqq:[^"]+)",\s*$', block)
        flag = re.search(r"(?m)^\s*(true|false),\s*$", block)
        caps = re.search(r"&\[(.*?)\]", block, re.DOTALL)
        if not (name and flag and caps):
            raise ValueError("an iface( entry stopped matching its shape")
        bound = flag.group(1) == "true"
        for variant in re.findall(r"([A-Za-z][A-Za-z0-9_]*)", caps.group(1)):
            if variant in out:
                raise ValueError(f"{variant} unlocked by two interfaces")
            out[variant] = (name.group(1), bound)
    if not out:
        raise ValueError("no iface( entries parsed; the table moved")
    return out


def parse_stanzas(text: str) -> dict[str, str]:
    """Typed `[capabilities.*]` stanza fields, excluding the `other` catch-all.

    Returns `field -> bracket`: `Vec<T>` fields are repeatable tables
    (`[[capabilities.fs]]`), `Option<T>` fields are single tables
    (`[capabilities.http]`). Stating the wrong bracket would print a spelling
    `qqq.toml` rejects, so the shape is derived from the type, not assumed.
    """
    lines = text.splitlines()
    try:
        start = next(
            i
            for i, line in enumerate(lines)
            if line.strip() == "pub struct Capabilities {"
        )
    except StopIteration:
        raise ValueError("pub struct Capabilities not found")
    fields: dict[str, str] = {}
    for line in lines[start + 1 :]:
        stripped = line.strip()
        if stripped.startswith("pub other:"):
            break
        m = re.match(r"pub ([a-z][a-z0-9_]*)\s*:\s*(Option<|Vec<)", stripped)
        if m:
            fields[m.group(1)] = "[[" if m.group(2) == "Vec<" else "["
    if not fields:
        raise ValueError("no Capabilities stanza fields parsed; the struct moved")
    return fields


def build() -> list[tuple[str, str, str, str, str, str]]:
    """The catalogue rows, sorted by dotted capability name."""
    cap_text = CAPABILITY_RS.read_text(encoding="utf-8")
    reg_text = REGISTRY_RS.read_text(encoding="utf-8")
    man_text = MANIFEST_RS.read_text(encoding="utf-8")
    names = parse_names(cap_text)
    kinds = parse_kinds(cap_text)
    registry = parse_registry(reg_text)
    stanzas = parse_stanzas(man_text)

    rows: list[tuple[str, str, str, str, str, str]] = []
    for variant, dotted in names.items():
        if variant not in kinds:
            raise ValueError(f"{variant} ({dotted}) has no kind() arm")
        if variant not in registry:
            raise ValueError(
                f"{variant} ({dotted}) is unlocked by no registry interface"
            )
        namespace = dotted.split(".")[0]
        bracket = stanzas.get(namespace)
        if bracket is None:
            raise ValueError(f"{dotted} has no [capabilities.{namespace}] stanza")
        close = "]]" if bracket == "[[" else "]"
        interface, bound = registry[variant]
        rows.append(
            (
                namespace,
                dotted,
                kinds[variant],
                "true" if bound else "false",
                interface,
                f"{bracket}capabilities.{namespace}{close}",
            )
        )
    rows.sort(key=lambda r: r[1])
    if len(rows) != 24:
        raise ValueError(f"expected 24 capabilities, built {len(rows)}")
    if len({r[0] for r in rows}) != 13:
        raise ValueError("expected 13 namespaces")
    return rows


def render(rows: list[tuple[str, str, str, str, str, str]]) -> str:
    return HEADER + "".join("\t".join(row) + "\n" for row in rows)


def self_test() -> int:
    """Prove the parsers detect breakage, on synthetic input."""
    failures = 0

    def expect(label: str, ok: bool, detail: str = "") -> None:
        nonlocal failures
        print(
            f"  {'OK  ' if ok else 'FAIL'}  {label}{(' -- ' + detail) if detail and not ok else ''}"
        )
        if not ok:
            failures += 1

    # A variant that never reaches a `=>` arm is refused, not silently unkinded.
    try:
        parse_kinds("pub const fn kind(self) {\n            Self::Orphan\n")
        expect("a kind-less variant is refused", False)
    except ValueError as e:
        expect("a kind-less variant is refused", "without a kind arm" in str(e), str(e))

    # The bracket shape is derived from the field type: repeatable tables
    # use double brackets, and the committed catalogue must say so.
    try:
        stanzas = parse_stanzas(
            "pub struct Capabilities {\n"
            "    pub fs: Vec<FsCapability>,\n"
            "    pub http: Option<HttpCapability>,\n"
            "    pub other: BTreeMap<String, Value>,\n"
        )
        expect(
            "Vec fields render double brackets",
            stanzas == {"fs": "[[", "http": "["},
            str(stanzas),
        )
    except ValueError as e:
        expect("stanza shape parses", False, str(e))

    # A capability unlocked by two interfaces is refused, not double-counted.
    dup = (
        "        iface(\n"
        '            "qqq:a@1.0.0",\n'
        "            &[Foo],\n"
        "            true,\n"
        '            "x",\n'
        "        ),\n"
        "        iface(\n"
        '            "qqq:b@1.0.0",\n'
        "            &[Foo],\n"
        "            false,\n"
        '            "y",\n'
        "        ),\n"
    )
    try:
        parse_registry(dup)
        expect("a capability in two rows is refused", False)
    except ValueError as e:
        expect(
            "a capability in two rows is refused", "two interfaces" in str(e), str(e)
        )

    # A live build has the known shape: 24 capabilities, 13 namespaces.
    try:
        rows = build()
        expect("live build yields 24 rows", len(rows) == 24, f"got {len(rows)}")
        expect(
            "live build yields 13 namespaces",
            len({r[0] for r in rows}) == 13,
            f"got {len({r[0] for r in rows})}",
        )
        bound = sum(1 for r in rows if r[3] == "true")
        expect("live build yields 18 bound", bound == 18, f"got {bound}")
        # The drift path: a changed source changes the rendering, so `--check`
        # fails on a stale file rather than agreeing with it.
        flipped = [
            (ns, cap, kind, ("false" if b == "true" else "true"), iface, stanza)
            for ns, cap, kind, b, iface, stanza in rows
        ]
        expect(
            "a flipped flag changes the rendering",
            render(rows) != render(flipped),
        )
    except ValueError as e:
        expect("live build succeeds", False, str(e))

    print()
    if failures:
        print(f"CATALOGUE SELF-TEST FAILED -- {failures} case(s)")
        return 1
    print(
        "CATALOGUE SELF-TEST OK -- the parsers detect breakage and the live tree parses"
    )
    return 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    check_only = "--check" in sys.argv
    try:
        rows = build()
    except (OSError, ValueError) as e:
        print(f"FATAL: {e}")
        return 1
    generated = render(rows)
    if check_only:
        if not CATALOGUE.exists():
            print(
                f"FATAL: {CATALOGUE} does not exist; run tools/gen_capability_catalogue.py"
            )
            return 1
        current = CATALOGUE.read_text(encoding="utf-8")
        if current != generated:
            print(
                "FATAL: schema/capability-catalogue.tsv is out of date with the tree. "
                "Run `python tools/gen_capability_catalogue.py`."
            )
            for i, (a, b) in enumerate(
                zip(current.splitlines(), generated.splitlines()), start=1
            ):
                if a != b:
                    print(f"  first difference at line {i}:")
                    print(f"    committed: {a[:100]}")
                    print(f"    generated: {b[:100]}")
                    break
            else:
                print(
                    f"  the committed file has {len(current.splitlines())} lines and "
                    f"the generated one has {len(generated.splitlines())} lines"
                )
            return 1
        print(f"CATALOGUE OK -- {len(rows)} row(s) match the tree")
        return 0
    CATALOGUE.parent.mkdir(parents=True, exist_ok=True)
    # `write_bytes`, not `write_text`: the latter translates `\n` to
    # `os.linesep` on Windows, and this repository pins `eol=lf` (`§O-273`).
    CATALOGUE.write_bytes(generated.encode("utf-8"))
    print(f"wrote {CATALOGUE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
